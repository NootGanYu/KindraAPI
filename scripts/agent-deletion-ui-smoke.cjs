const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), http = require('node:http')
const { _electron } = require('playwright-core')
const { openAgentPanel } = require('./agent-ui-helper.cjs')
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'kindra-deletion-ui-'))
let app, pid, targetId, flowId
const server = http.createServer(async (req, res) => {
  let raw = ''; for await (const chunk of req) raw += chunk
  const body = JSON.parse(raw), probe = body.tools?.[0]?.function.name === 'kindra_capability_probe'
  const message = body.tools ? { tool_calls: [{ id: 'call', type: 'function', function: { name: probe ? 'kindra_capability_probe' : flowId ? 'propose_flow_change' : 'propose_api_change', arguments: JSON.stringify(probe ? { token: 'kindra-probe' } : { project_id: pid, ...(flowId ? {flow_id:flowId} : {target_id:targetId}), patch: { description: '删除后可恢复的候选说明' } }) } }] } : { content: '完成' }
  res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({ choices: [{ message }] }))
})
const launch = () => _electron.launch({ args: [path.resolve(__dirname, '../out/main/index.js')], env: { ...process.env, KINDRAAPI_USER_DATA: userData, KINDRAAPI_DISABLE_SINGLE_INSTANCE: '1' } })
;(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  app = await launch(); let page = await app.firstWindow(); await page.getByRole('button', { name: '打开 Agent' }).waitFor()
  const seed = await page.evaluate(async base => {
    const p = (await window.api.projects.ensureDefault()).data
    const target = (await window.api.targets.create(p.project_id, '0', 'api')).data
    target.name = '删除后的接口'; await window.api.targets.save(p.project_id, target)
    await window.api.agent.saveConnection({ name: '删除恢复', base_url: base, model: 'delete-ui', protocol: 'chat-completions' }); await window.api.agent.testConnection()
    return { pid: p.project_id, targetId: target.target_id }
  }, `http://127.0.0.1:${server.address().port}/v1`)
  pid = seed.pid; targetId = seed.targetId
  await page.evaluate(async ({pid, targetId}) => { const p = await window.api.agent.proposeEditPlan(pid, {goal:'修改说明',targetId}); if (!p.ok) throw new Error(p.error); const a = await window.api.agent.approvePlan(pid,p.data.plan_id); if (!a.ok) throw new Error(a.error) }, seed)
  await openAgentPanel(page)
  await page.getByRole('button', { name: '项目候选汇总', exact: true }).click()
  await page.getByText('已正式保存', { exact: true }).waitFor()
  await page.evaluate(async ({pid,targetId}) => { const r = await window.api.targets.delete(pid,targetId); if (!r.ok) throw new Error(r.error) },seed)
  await page.getByText('对象已删除', { exact: true }).waitFor()
  await page.getByRole('button', { name: '查看删除墓碑', exact: true }).click()
  await page.getByText('删除墓碑', { exact: true }).waitFor()
  await page.getByRole('button', { name: '审阅候选', exact: true }).click()
  await page.getByRole('button', { name: '不采纳', exact: true }).click()
  await page.getByText('未采纳', { exact: true }).waitFor()
  await app.evaluate(({app}) => app.exit(0)); app = await launch(); page = await app.firstWindow()
  await openAgentPanel(page)
  await page.getByRole('button', { name: '项目候选汇总', exact: true }).click()
  await page.getByRole('button', { name: '审阅候选', exact: true }).click()
  await page.getByText('未采纳', { exact: true }).waitFor()
  await page.getByRole('button', { name: '恢复到草稿', exact: true }).click()
  await page.getByText('已应用草稿', { exact: true }).waitFor()
  assert.equal(await page.evaluate(async ({pid,targetId}) => (await window.api.targets.get(pid,targetId)).data, seed), null)
  await page.getByRole('button', { name: '恢复删除前草稿', exact: true }).click()
  await page.getByRole('button', { name: '正式保存恢复草稿', exact: true }).click()
  await page.getByText('已正式保存', { exact: true }).waitFor()
  assert.equal(await page.evaluate(async ({pid,targetId}) => (await window.api.targets.get(pid,targetId)).data.description, seed), '删除后可恢复的候选说明')
  console.log('PASS Electron live deletion refresh, tombstone review, reject/restart, restore-only then explicit recovery save')
  await page.evaluate(async ({pid,targetId}) => {
    const init = await window.api.git.init(pid); if (!init.ok) throw new Error(init.error)
    const discarded = await window.api.git.discard(pid, [{path:`apis/${targetId}.json`,untracked:true}]); if (!discarded.ok) throw new Error(discarded.error)
  }, seed)
  await page.getByText('对象已删除', { exact: true }).waitFor()
  await page.getByRole('button', { name: '恢复删除前草稿', exact: true }).click()
  await page.getByRole('button', { name: '正式保存恢复草稿', exact: true }).click()
  await page.getByText('已正式保存', { exact: true }).waitFor()
  console.log('PASS Electron Git discard deletion retains candidate evidence and can explicitly restore the definition')
  await page.getByRole('button', { name: '返回对话', exact: true }).click()
  flowId = await page.evaluate(async pid => (await window.api.flows.create(pid,'删除后的流程')).data.flow_id, pid)
  await page.evaluate(async ({pid,flowId}) => {
    const p = await window.api.agent.proposeEditPlan(pid,{goal:'修改流程',targetId:'',flowIds:[flowId]}); if (!p.ok) throw new Error(p.error)
    const a = await window.api.agent.approvePlan(pid,p.data.plan_id); if (!a.ok) throw new Error(a.error)
    const d = await window.api.flows.delete(pid,flowId); if (!d.ok) throw new Error(d.error)
  }, {pid,flowId})
  await page.getByRole('button', { name: '项目候选汇总', exact: true }).click()
  const flowCard = page.locator('.ant-card').filter({has:page.getByText('删除后的流程',{exact:true})})
  await flowCard.getByText('对象已删除',{exact:true}).waitFor()
  await flowCard.getByRole('button',{name:/^Flow 版本/}).click()
  const versions = page.getByRole('dialog',{name:'Flow 版本',exact:true})
  await versions.getByRole('button',{name:'不采纳',exact:true}).click()
  await versions.getByText('未采纳',{exact:true}).waitFor()
  await versions.getByRole('button',{name:'恢复候选到草稿',exact:true}).click()
  await versions.getByText('已应用草稿',{exact:true}).waitFor()
  await versions.locator('.ant-drawer-close').click()
  assert.equal(await page.evaluate(async ({pid,flowId}) => (await window.api.flows.get(pid,flowId)).data,{pid,flowId}),null)
  await flowCard.getByRole('button',{name:'恢复删除前草稿',exact:true}).click()
  await flowCard.getByRole('button',{name:'正式保存恢复草稿',exact:true}).click()
  await flowCard.getByText('已正式保存',{exact:true}).waitFor()
  assert.equal(await page.evaluate(async ({pid,flowId}) => (await window.api.flows.get(pid,flowId)).data.description,{pid,flowId}),'删除后可恢复的候选说明')
  console.log('PASS Electron deleted Flow project-summary review, rejection, candidate recovery and separate formal save')
})().catch(async error => { if (app) { const page = await app.firstWindow(); await page.screenshot({ path: '/tmp/kindra-builtin-agent-context/deletion-ui-21.png' }); console.error((await page.locator('body').innerText()).slice(-4000)) }; console.error(error); process.exitCode = 1 }).finally(async () => { if (app) await app.evaluate(({app})=>app.exit(0)).catch(()=>{}); server.closeAllConnections(); server.close() })
