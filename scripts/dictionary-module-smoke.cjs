run().catch(async error => {
  console.error(error)
  if (page) await page.screenshot({ path: '/tmp/kindra-dictionary-failure.png' }).catch(() => {})
  process.exitCode = 1
}).finally(async () => {
  try { if (app) await app.evaluate(({ app }) => app.exit(0)).catch(() => {}) }
  finally {
    fs.rmSync(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 })
    if (mysqlFixture) await mysqlFixture.close()
  }
})
